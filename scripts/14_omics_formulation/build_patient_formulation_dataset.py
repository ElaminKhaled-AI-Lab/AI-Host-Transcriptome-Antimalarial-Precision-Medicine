#!/usr/bin/env python
"""Phase 20 -- build the patient x formulation dataset for PROFILE-Net.

Couples the REAL paediatric cohort (or the best available fallback) to the
nano drug-delivery-system (DDS) design space, producing one row per
(child, formulation) with mechanistically generated outcomes.

Patient side  : age, weight, host metabolic proxy, host toxicity proxy,
                parasite resistance burden -- taken from the real dual-RNA
                cohort where available (see src/utils/patient_cohort.py).
Formulation side: the coded factors plus the full predicted characterization
                (size, PDI, zeta, entrapment efficiency, drug loading,
                dissolution efficiency, mean dissolution time, t50,
                Korsmeyer-Peppas n, liver-targeting index) and polymer descriptors.
Outcomes      : day-7 exposure (the clinical predictor of cure) and cure, both
                generated by the project pharmacokinetic model with two genuine
                patient-by-formulation interactions built in --
                  (i) host metabolic capacity scales clearance, which interacts
                      with the formulation's bioavailable fraction; and
                  (ii) parasite resistance is offset by liver targeting, so the
                      best formulation genuinely differs between children.

Output -> data/synthetic/patient_formulation_dataset.parquet (TSV fallback)
"""
import _bootstrap  # noqa: F401
import argparse
import itertools

import numpy as np
import pandas as pd

from src.utils.config import get_path, load_config
from src.utils.logging_utils import get_logger
from src.utils.patient_cohort import load_patients
from src.models.nano_dds import (
    Formulation, POLYMERS, release_profile, predict_size, predict_pdi,
    predict_zeta, predict_ee, predict_dl, liver_targeting_index,
    RATIO_MAP, STAB_MAP, ENERGY_MAP)
from src.models.dissolution_metrics import (
    dissolution_efficiency, mean_dissolution_time, time_to_percent, fit_all_models)

log = get_logger(__name__)

TIMES = np.array([0.25, 0.5, 1, 2, 4, 6, 8, 12, 16, 24, 36, 48, 72], float)
LEVELS = (-1, 0, 1)


def formulation_library(drug, stabilizer, polymers):
    """Characterize every (polymer x 27-run) formulation once, up front."""
    lib = []
    for polymer in polymers:
        for run_id, (a, b, c) in enumerate(itertools.product(LEVELS, LEVELS, LEVELS), 1):
            f = Formulation(drug=drug, polymer=polymer, stabilizer=stabilizer,
                            polymer_drug_ratio=a, stabilizer_pct=b, homogenization=c)
            t, Q = release_profile(f, TIMES)
            kp = fit_all_models(t, Q).get("korsmeyer_peppas", {})
            p = POLYMERS[polymer]
            lib.append({
                "formulation_id": f"{polymer}_r{run_id}", "polymer": polymer, "run": run_id,
                "A": a, "B": b, "C": c,
                "ratio": RATIO_MAP[a], "stab_pct": STAB_MAP[b], "energy": ENERGY_MAP[c],
                "size_nm": predict_size(f), "pdi": predict_pdi(f), "zeta_mv": predict_zeta(f),
                "ee_pct": predict_ee(f), "dl_pct": predict_dl(f),
                "DE_pct": dissolution_efficiency(t, Q), "MDT_h": mean_dissolution_time(t, Q),
                "t50_h": time_to_percent(t, Q, 50),
                "n_peppas": kp.get("n") if kp.get("n") is not None else 0.5,
                "liver_idx": liver_targeting_index(f),
                "poly_basesize": p["base_size_nm"], "poly_zeta": p["zeta_mv"],
                "poly_degrad": p["degrad"],
                "Q24": float(np.interp(24, t, Q)),
                "burst_1h": float(np.interp(1.0, t, Q)),
            })
    return pd.DataFrame(lib)


def outcomes(patients, lib, drug):
    """Mechanistic day-7 exposure and cure for every (child, formulation) pair."""
    from src.models.pharmacokinetics import (
        DRUGS as PKDRUGS, scale_params, PKParams, exposure_metrics, cure_probability)
    cls = drug if drug in PKDRUGS else "lumefantrine"

    rows = []
    for pat in patients.itertuples():
        # formulation-dependent bioavailable fraction
        F = np.clip(0.30 + 0.50 * lib["ee_pct"].to_numpy() / 100
                    + 0.20 * lib["Q24"].to_numpy() / 100, 0.10, 1.0)
        CL, V, ka, dose = scale_params(cls, pat.weight_kg, pat.age_years)
        # interaction (i): host metabolic capacity scales clearance
        CL = CL * float(np.exp(0.25 * pat.host_metabolic_z))
        day7 = np.empty(len(lib))
        for i, Fi in enumerate(F):
            m = exposure_metrics(PKParams(CL=float(CL), V=float(V), ka=float(ka),
                                          F=float(Fi), dose_mg=float(dose)))
            day7[i] = m["day7"]
        cure = cure_probability(day7, cls)
        # interaction (ii): resistance is offset by liver targeting
        cure = cure * (1.0 - 0.6 * pat.parasite_resistance * (1.0 - lib["liver_idx"].to_numpy()))
        cure = np.clip(cure, 0, 1)

        # interaction (iii): THERAPEUTIC WINDOW. Exposure far above target becomes
        # harmful, and susceptibility scales with the host toxicity proxy, while a
        # large burst release raises peak concentration. A child who clears the
        # drug slowly therefore prefers a lower-exposure, sustained formulation,
        # whereas a fast metaboliser needs a high-exposure one -- so the OPTIMAL
        # formulation genuinely differs between children (a crossover interaction,
        # not merely a change of magnitude).
        target = PKDRUGS[cls].get("day7_target") or float(np.median(day7))
        exposure_index = day7 / max(target, 1e-9)
        burst_frac = lib["burst_1h"].to_numpy() / 100.0
        tox = 1.0 / (1.0 + np.exp(-1.2 * (exposure_index - 8.0)))
        tox = np.clip(tox * float(np.exp(0.35 * pat.host_tox_z)) * (1.0 + 0.3 * burst_frac), 0, 1)
        utility = cure * (1.0 - tox)          # therapeutic utility: efficacy net of harm

        rng = np.random.default_rng(abs(hash(pat.patient_id)) % (2 ** 31))
        cure_bin = (rng.uniform(size=len(cure)) < cure).astype(int)
        blk = lib.copy()
        blk["patient_id"] = pat.patient_id
        blk["age_years"] = pat.age_years
        blk["weight_kg"] = pat.weight_kg
        blk["host_metabolic_z"] = pat.host_metabolic_z
        blk["host_tox_z"] = pat.host_tox_z
        blk["parasite_resistance"] = pat.parasite_resistance
        blk["day7_ng_per_mL"] = day7
        blk["log10_day7"] = np.log10(np.clip(day7, 1e-3, None))
        blk["cure_prob"] = cure
        blk["toxicity_risk"] = tox
        blk["utility"] = utility
        blk["cure"] = cure_bin
        rows.append(blk)
    return pd.concat(rows, ignore_index=True)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--drug", default="lumefantrine")
    ap.add_argument("--stabilizer", default="PVA")
    ap.add_argument("--polymers", nargs="*", default=list(POLYMERS))
    ap.add_argument("--site", default="mali", help="real cohort site to prefer")
    ap.add_argument("--max-patients", type=int, default=None)
    args = ap.parse_args()
    load_config()

    patients = load_patients(prefer_site=args.site, paediatric_only=True)
    if args.max_patients:
        patients = patients.head(args.max_patients)
    log.info("cohort: %d children | source=%s | age source=%s | age %.1f-%.1f y",
             len(patients), patients["source"].iloc[0], patients["age_source"].iloc[0],
             patients["age_years"].min(), patients["age_years"].max())

    lib = formulation_library(args.drug, args.stabilizer, args.polymers)
    log.info("formulation library: %d formulations (%d polymers x 27 runs)",
             len(lib), len(args.polymers))

    df = outcomes(patients, lib, args.drug)
    df["drug"] = args.drug
    syn = get_path("data_synthetic", create=True)
    try:
        out = syn / "patient_formulation_dataset.parquet"
        df.to_parquet(out, index=False)
    except Exception:
        out = syn / "patient_formulation_dataset.tsv"
        df.to_csv(out, sep="\t", index=False)
    # also persist the cohort actually used
    patients.to_csv(get_path("tables", create=True) / "paediatric_cohort_used.csv", index=False)

    log.info("dataset: %d rows (%d children x %d formulations)", len(df),
             patients.shape[0], len(lib))
    log.info("day-7 exposure %.1f-%.1f ng/mL | mean cure %.2f | mean toxicity %.2f | "
             "mean utility %.2f", df.day7_ng_per_mL.min(), df.day7_ng_per_mL.max(),
             df.cure_prob.mean(), df.toxicity_risk.mean(), df.utility.mean())
    # how often does the best formulation differ between children?
    best_per_pat = df.loc[df.groupby("patient_id")["utility"].idxmax()]
    log.info("distinct optimal formulations across %d children: %d",
             df.patient_id.nunique(), best_per_pat.formulation_id.nunique())
    log.info("wrote %s and tables/paediatric_cohort_used.csv", out)


if __name__ == "__main__":
    main()
