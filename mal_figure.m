function fig = mal_figure(widthCM, heightCM)
%MAL_FIGURE  Create a white, Arial-styled figure of a given physical size.
C = mal_cfg();
if nargin < 1 || isempty(widthCM),  widthCM  = C.figW; end
if nargin < 2 || isempty(heightCM), heightCM = C.figH; end
figColour = 'w'; if strcmpi(C.background,'none'), figColour = 'none'; end
fig = figure('Color',figColour,'Units','centimeters', ...
    'Position',[2 2 widthCM heightCM], ...
    'PaperUnits','centimeters','PaperPosition',[0 0 widthCM heightCM], ...
    'PaperSize',[widthCM heightCM],'InvertHardcopy','off');
set(fig, 'DefaultAxesFontName',C.fontName, 'DefaultAxesFontSize',C.fsAxis, ...
         'DefaultTextFontName',C.fontName, 'DefaultTextFontSize',C.fsAxis, ...
         'DefaultAxesLineWidth',C.axisWidth, 'DefaultLineLineWidth',C.lineWidth);
end
